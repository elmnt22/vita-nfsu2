"""Writes xp_manifest.inc: the MW / Carbon files the expansion reads (name, size, CRC32).
usage: python gen_xp_manifest.py MW_DIR CARBON_DIR"""
import sys, os, zlib
SETS = {1: ["TRACKS/STREAML2RA.BUN", "TRACKS/L2RA.BUN", "TRACKS/L2RA/MINI_MAP.BIN", "GLOBAL/attributes.bin", "GLOBAL/gameplay.bin"],
        2: ["TRACKS/STREAML5RA.BUN", "TRACKS/L5RA.BUN", "GLOBAL/attributes.bin", "GLOBAL/gameplay.bin"]}
out = ["/* generated by gen_xp_manifest.py: { game, file, size, crc32 } */"]
for game, root in ((1, sys.argv[1]), (2, sys.argv[2])):
    for rel in SETS[game]:
        p = os.path.join(root, rel); c = 0
        with open(p, 'rb') as f:
            while True:
                b = f.read(1 << 22)
                if not b: break
                c = zlib.crc32(b, c)
        out.append('    { %d, "%s", %dLL, 0x%08xu },' % (game, rel, os.path.getsize(p), c))
open('xp_manifest.inc', 'w').write('\n'.join(out) + '\n')
print('\n'.join(out))
