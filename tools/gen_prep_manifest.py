"""Build converter/game_manifest.inc for the NFSU2 Vita Prep Tool.

    python tools/gen_prep_manifest.py <NFSU2 v1.2 game folder>

Lists every game file the Vita port needs (the folders the README tells
players to copy) with its size and CRC32. The Prep Tool checks the player's
install against it and copies / sends only these files. Only names, sizes and
checksums go into the list -- no game data.

Left out on purpose (the port never opens them):
  - Support, Uninstall, #JIMBO and the files in the install's root
  - SOUND/ENGINE/CAR_nn_ENG_MB_EE.ABK: the port loads the _SPU engine banks
    (audio.c), the _EE copies are never read
"""
import os
import re
import sys
import zlib

FOLDERS = ["CARS", "CREDITS", "FRONTEND", "GLOBAL", "LANGUAGES", "MOVIES", "NIS",
           "SDATA", "SOUND", "SUBTITLES", "TRACKS", "memcard"]
SKIP = [re.compile(r"^SOUND/ENGINE/CAR_\d+_ENG_MB_EE\.ABK$", re.I)]
# The reference copy's SDATA/sdat.viv lost its last 832 bytes (zeros, the end of
# speech/nisaudio.big). This is the CRC of a good retail copy, same size.
CRC_FIX = {"SDATA/sdat.viv": (259484480, 0x34ff63a3)}


def crc32(path):
    c = 0
    with open(path, "rb") as f:
        while True:
            b = f.read(1 << 20)
            if not b:
                return c & 0xFFFFFFFF
            c = zlib.crc32(b, c)


def main():
    game = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "converter", "game_manifest.inc")
    rows, skipped, total = [], 0, 0
    for top in FOLDERS:
        base = os.path.join(game, top)
        if not os.path.isdir(base):
            sys.exit("missing folder " + base)
        for d, _, files in os.walk(base):
            for n in files:
                p = os.path.join(d, n)
                rel = os.path.relpath(p, game).replace("\\", "/")
                if any(s.match(rel) for s in SKIP):
                    skipped += 1
                    continue
                sz = os.path.getsize(p)
                c = crc32(p)
                if rel in CRC_FIX and CRC_FIX[rel][0] == sz:
                    c = CRC_FIX[rel][1]
                rows.append((rel, sz, c))
                total += sz
    rows.sort(key=lambda r: r[0].lower())
    with open(out, "w", newline="\n") as f:
        f.write("/* AUTO-GENERATED by tools/gen_prep_manifest.py from the NFSU2 PC v1.2 data -- do not edit.\n")
        f.write(" * %d files, %d bytes (%d unused files left out). Names, sizes and CRC32s only. */\n"
                % (len(rows), total, skipped))
        for rel, sz, c in rows:
            f.write('{ "%s", %dLL, 0x%08xu },\n' % (rel.replace('"', '\\"'), sz, c))
    print("%d files, %.1f MB, %d left out -> %s" % (len(rows), total / 1048576.0, skipped, out))


if __name__ == "__main__":
    main()
