# Generates sim/include/sim_gl.h + sim/sim_gl.c: every OpenGL ES 2.0 entry
# point as a function pointer loaded through SDL_GL_GetProcAddress once the
# simulator's ES context exists (Windows' opengl32.dll exports only GL 1.1).
#   python sim/gen_gl.py <SDL2 include dir>
import os, re, sys

inc = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(inc, 'SDL_opengles2_gl2.h'), encoding='latin1').read()
names = re.findall(r'typedef [^;]*?\(GL_APIENTRYP (PFNGL\w+PROC)\)', src)
funcs = []
for pfn in names:
    m = re.search(r'GL_APIENTRY (gl\w+)\s*\(', src[src.index('#if GL_GLES_PROTOTYPES'):])
    break
for m in re.finditer(r'GL_APICALL [^;]*?GL_APIENTRY (gl\w+)\s*\(', src):
    funcs.append(m.group(1))
funcs = sorted(set(funcs))
pfn = {f: 'PFN' + f.upper() + 'PROC' for f in funcs}
missing = [f for f in funcs if pfn[f] not in names]
assert not missing, missing

h = ['/* sim_gl.h -- generated by sim/gen_gl.py: GL ES 2.0 through pointers. */',
     '#ifndef SIM_GL_H', '#define SIM_GL_H', '#ifdef __cplusplus', 'extern "C" {', '#endif',
     'int sim_gl_load(void);']
for f in funcs:
    h.append('extern %s sim_%s;' % (pfn[f], f))
    h.append('#define %s sim_%s' % (f, f))
h += ['#ifdef __cplusplus', '}', '#endif', '#endif', '']
open(os.path.join(here, 'include', 'sim_gl.h'), 'w').write('\n'.join(h))

c = ['/* sim_gl.c -- generated by sim/gen_gl.py */',
     '#include "SDL.h"', '#include "SDL_opengles2.h"', '#include <stdio.h>']
for f in funcs:
    c.append('%s sim_%s;' % (pfn[f], f))
c.append('int sim_gl_load(void) {')
c.append('    int missing = 0;')
for f in funcs:
    c.append('    if (!(sim_%s = (%s)SDL_GL_GetProcAddress("%s"))) { printf("sim: GL entry %s missing\\n"); missing++; }'
             % (f, pfn[f], f, f))
c.append('    return missing;')
c.append('}')
open(os.path.join(here, 'sim_gl.c'), 'w').write('\n'.join(c) + '\n')
print(len(funcs), 'GL entry points')
